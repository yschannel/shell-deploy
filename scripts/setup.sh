#!/usr/bin/env bash

check_system() {
    local ID=""
    local VERSION_ID=""
    local PRETTY_NAME=""

    log_info "正在检查操作系统......"

    if [[ ! -r /etc/os-release ]]; then
        log_error "无法读取 /etc/os-release, 不能确定当前系统"
        return 1
    fi

    if ! source /etc/os-release; then
        log_error "读取操作系统信息失败"
        return 1
    fi

    if [[ "$ID" != "ubuntu" ]]; then
        log_error "当前系统：${PRETTY_NAME:-未知}"
        log_error "本工具第一版仅支持 ubuntu"
        return 1
    fi

    log_success "当前系统: ${PRETTY_NAME:-Ubuntu}"
    log_info "系统版本: ${VERSION_ID:-未知}"

    return 0
}

check_dependencies() {
    local tool
    local answer
    local -a required_tools=(g++ make curl ss flock)
    local -a missing_tools=()
    local -a missing_packages=()

    log_info "正在检查项目依赖......"

    for tool in "${required_tools[@]}"; do
        if command -v "$tool" > /dev/null 2>&1; then
            log_success "已安装 $tool"
        else
            log_info "缺少 $tool"
            missing_tools+=("$tool")
	    case "$tool" in
		ss)
		    missing_packages+=(iproute2)
		    ;;
		flock)
		    missing_packages+=(util-linux)
		    ;;
		*)
		    missing_packages+=("$tool")
		    ;;
	    esac
        fi
    done

    # 依赖齐全时，直接结束本函数。
    if (( ${#missing_tools[@]} == 0 )); then
        log_success "依赖检查通过"
        return 0
    fi

    log_info "需要安装：${missing_tools[*]}"

    if ! read -r -p "是否安装缺少的依赖？[y/N]: " answer; then
        log_error "未能读取用户输入，初始化停止"
        return 1
    fi

    case "$answer" in
        y|Y|yes|YES)
            log_info "用户同意安装依赖"
            ;;
        *)
            log_error "未同意安装，初始化停止"
            return 1
            ;;
    esac

    if ! command -v sudo > /dev/null 2>&1; then
        log_error "未找到 sudo，无法通过本流程安装依赖"
        return 1
    fi

    if ! sudo apt-get update; then
        log_error "软件包信息更新失败，初始化停止"
        return 1
    fi

    if ! sudo apt-get install -y "${missing_packages[@]}"; then
        log_error "依赖安装失败，初始化停止"
        return 1
    fi

    # 安装命令成功后，重新检查工具是否可用。
    for tool in "${required_tools[@]}"; do
        if ! command -v "$tool" > /dev/null 2>&1; then
            log_error "安装后仍未找到 $tool,初始化停止"
            return 1
        fi
    done

    log_success "依赖安装完成，检查通过"
    return 0
}

collect_configuration() {
    local choice
    local port_input
    local data_input

    #后面的函数也要读取，所以这里不使用local
    PORT=8080
    DATA_DIR="$PROJECT_ROOT/data"

    printf '\n请选择配置方式：\n'
    printf '1.使用默认配置\n'
    printf '2.自定义配置\n'

    while true; do
        if ! read -r -p "请输入 [1]:" choice; then
            log_error "未能读取输入，初始化停止"
	    return 1
        fi

	choice="${choice:-1}"

        case "$choice" in
            1)
		break
		;;
            2)
		#收集端口。
		while true; do
		    if ! read -r -p "请输入服务端口[8080]:" port_input; then
			log_error "未能读取端口，初始化停止"
			return 1
		    fi

		    port_input="${port_input:-8080}"

		    if [[ ! "$port_input" =~ ^[0-9]{1,5}$ ]]; then
			log_error "端口必须是1到65535的整数"
			continue
		    fi

		    PORT=$((10#$port_input))

		    if (( PORT < 1 || PORT > 65535 )); then
			log_error "端口必须在1到65535之间"
			continue
		    fi

		    if (( PORT < 1024 )); then
			log_error "本工具使用普通用户启动服务，请选择1024到65535"
			continue
		    fi

		    break
		done

		#收集数据目录
		if ! read -r -p "请输入数据目录 [./data]: " data_input; then
		    log_error "未能读取数据目录，初始化停止"
		    return 1
		fi

		data_input="${data_input:-./data}"

		if [[ "$data_input" == /* ]]; then
		    DATA_DIR="$data_input"
		else
		    DATA_DIR="$PROJECT_ROOT/$data_input"
		fi

		break
		;;
	    *)
		log_error "请输入 1 或 2"
		;;
	    esac
	done

	printf '\n'
	log_info "服务端口: $PORT"
	log_info "数据目录：$DATA_DIR"

	return 0
}

prepare_project_files() {
    local config_file="$PROJECT_ROOT/config.conf"
    local temp_file
    local directory

    log_info "正在准备目录和配置文件......"

    # -e 检查文件是否存在，-L 也检查符号链接。
    if [[ -e "$config_file" || -L "$config_file" ]]; then
	log_error "配置文件已存在：$config_file"
        log_error "为保留已有配置，本次初始化停止"
	return 1
    fi

    # 创建运行目录和用户选择的数据目录。
    if ! mkdir -p -- \
	"$PROJECT_ROOT/bin" \
	"$PROJECT_ROOT/logs" \
	"$PROJECT_ROOT/run" \
        "$DATA_DIR"; then
	log_error "目录创建失败，请检查路径和权限"
	return 1
    fi

    # 确认当前用户可以写入这些目录。
    for directory in \
	"$PROJECT_ROOT/bin" \
	"$PROJECT_ROOT/logs" \
	"$PROJECT_ROOT/run" \
        "$DATA_DIR"; do

	if [[ ! -d "$directory" || ! -w "$directory" || ! -x "$directory" ]]; then
	    log_error "目录不可用或没有所需权限：$directory"
	    return 1
	fi
    done

    log_success "运行记录和数据目录已准备"

    # 先写临时文件，避免留下只写了一半的正式配置。
    if ! temp_file="$(mktemp "$PROJECT_ROOT/.config,conf.XXXXXX")"; then
	log_error "无法创造临时配置文件"
	return 1
    fi

    if ! {
	printf '# Generated by deploy.sh; Bash syntax\n'
	printf 'PORT=%q\n' "$PORT"
	printf 'DATA_DIR=%q\n' "$DATA_DIR"
    } > "$temp_file"; then
	rm -f -- "$temp_file"
	log_error "配置写入失败"
	return 1
    fi

    # 创建正式配置，如果目标已存在， ln 会失败，不会覆盖。
    if ! ln -- "$temp_file" "$config_file"; then
        rm -f -- "$temp_file"
	log_error "无法生成配置文件，目标可能已经存在或目录权限不足"
	return 1
    fi

    rm -f -- "$temp_file"

    log_success "配置文件已生成：$config_file"
    return 0
}

build_application() {
    local build_log="$PROJECT_ROOT/logs/build.log"

    log_info "正在编译应用......"

    if [[ ! -f "$PROJECT_ROOT/Makefile" ]]; then
	log_error "未找到 Makefile, 无法编译"
	return 1
    fi

    if ! make -C "$PROJECT_ROOT" > "$build_log" 2>&1; then
	log_error "编译失败，日志位置：$build_log"
	log_info "以下为最后20行编译日志："
	tail -n 20 -- "$build_log" >&2
	return 1
    fi

    if [[ ! -f "$PROJECT_ROOT/bin/app" || ! -x "$PROJECT_ROOT/bin/app" ]]; then
	log_error "构建命令已完成，但未生成可执行文件 bin/app"
	log_error "请检查 Makefile 的输出位置"
	return 1
    fi

    log_success "应用构建完成：$PROJECT_ROOT/bin/app"
    return 0
}

setup_project() {
    log_info "开始初始化项目"
    log_info "项目目录：$PROJECT_ROOT"

    check_system || return 1
    check_dependencies || return 1
    collect_configuration || return 1
    prepare_project_files || return 1
    build_application || return 1

    log_success "初始化成功"
    log_info "启动命令：bash deploy.sh start"
}
